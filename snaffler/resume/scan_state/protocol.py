"""Protocol defining the state store API for type-safe facade delegation."""

from typing import Any, Iterator, Protocol


class StateStoreProtocol(Protocol):
    """Structural type for state store backends.

    ``SQLiteStateStore`` satisfies this protocol via its mixin composition.
    The ``ScanState`` facade delegates to this interface.
    """

    # -- sync / phase flags --

    def get_sync_flag(self, key: str) -> bool: ...
    def set_sync_flag(self, key: str) -> None: ...
    def get_sync_value(self, key: str) -> str | None: ...
    def set_sync_value(self, key: str, value: str) -> None: ...
    def clear_phase_flags(self) -> None: ...

    # -- lifecycle --

    def close(self) -> None: ...

    # -- computers --

    def store_computers(self, computers: list[str]) -> None: ...
    def load_computers(self) -> list[str]: ...
    def update_computer_ip(self, name: str, ip: str) -> None: ...
    def load_resolved_computers(self) -> list[str]: ...
    def load_unresolved_computers(self) -> list[str]: ...
    def has_checked_computer(self, name: str) -> bool: ...
    def mark_computer_checked(self, name: str) -> None: ...
    def count_checked_computers(self) -> int: ...

    # -- shares --

    def store_shares(self, shares: list[str | tuple[str, bool]]) -> None: ...
    def load_shares(self) -> list[str]: ...
    def load_unreadable_shares(self) -> list[str]: ...
    def update_share_readable(self, unc_path: str) -> None: ...
    def has_checked_share(self, unc_path: str) -> bool: ...
    def mark_share_checked(self, unc_path: str) -> None: ...
    def count_checked_shares(self) -> int: ...

    # -- files --

    def load_checked_files(self) -> set[str]: ...
    def iter_checked_file_keys(self) -> Iterator[str]: ...
    def is_file_checked(self, path_lower: str) -> bool: ...
    def mark_file_checked(self, unc_path: str) -> None: ...
    def mark_files_checked_batch(self, paths: list[str]) -> None: ...
    def store_file(self, unc_path: str, share: str, size: int = 0, mtime: float = 0.0) -> None: ...
    def store_files(self, files: list[tuple[str, str, int, float]]) -> None: ...
    def load_unchecked_files(self) -> list[tuple[str, int, float]]: ...
    def iter_unchecked_files(self) -> Iterator[tuple[str, int, float]]: ...
    def count_target_files(self) -> int: ...
    def count_checked_files(self) -> int: ...

    # -- directories --

    def store_dir(self, unc_path: str, share: str) -> None: ...
    def store_dirs(self, dirs: list[tuple[str, str]]) -> None: ...
    def mark_dir_walked(self, unc_path: str) -> None: ...
    def load_unwalked_dirs(self, share: str | None = None) -> list[str]: ...
    def load_walked_dirs(self) -> list[str]: ...

    # -- findings --

    def store_finding(
        self,
        finding_id: str,
        file_path: str,
        triage: str,
        rule_name: str,
        match_text: str | None = None,
        context: str | None = None,
        size: int | None = None,
        mtime: str | None = None,
        found_at: str | None = None,
    ) -> None: ...
    def load_findings(self) -> list[dict[str, Any]]: ...
    def count_findings(self) -> int: ...
    def count_findings_by_triage(self) -> dict[str, int]: ...
